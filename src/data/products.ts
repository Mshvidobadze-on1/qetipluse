export const calculateInstallment = (
  price: number,
  bank: BankId,
  months: number
): { monthly: number; total: number; effectiveRate: number } => {
  let annualRate = 0;
  if (months <= 3) {
    annualRate = 0;
  } else if (months <= 6) {
    annualRate = bank === 'credo' ? 6.5 : 0;
  } else if (months === 12) {
    annualRate = bank === 'tbc' ? 11.9 : bank === 'bog' ? 11.5 : 13.5;
  } else {
    annualRate = bank === 'tbc' ? 13.9 : bank === 'bog' ? 13.5 : 15.2;
  }

  if (annualRate === 0) {
    return {
      monthly: Math.round(price / months),
      total: price,
      effectiveRate: 0,
    };
  }

  const total = Math.round(price * (1 + (annualRate / 100) * (months / 12)));
  return {
    monthly: Math.round(total / months),
    total,
    effectiveRate: annualRate,
  };
};

